#!/usr/bin/env bash
# Builds the Cerberus Sentinel macOS app and packages it as Cerberus-macOS-universal.dmg
# in the repository root. Requires Go, Node.js/npm and the Wails v2 CLI.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FRONT_DIR="${ROOT_DIR}/front"
DESKTOP_DIR="${ROOT_DIR}/desktop"
EMBED_DIR="${DESKTOP_DIR}/frontend/dist"
OUTPUT_DMG="${ROOT_DIR}/Cerberus-macOS-universal.dmg"

# Wails is installed by `go install`, which puts it in $(go env GOPATH)/bin.
if ! command -v wails >/dev/null 2>&1 && command -v go >/dev/null 2>&1; then
  export PATH="$(go env GOPATH)/bin:${PATH}"
fi
for tool in go npm wails; do
  if ! command -v "${tool}" >/dev/null 2>&1; then
    echo "Error: '${tool}' not found in PATH." >&2
    [ "${tool}" = "wails" ] && echo "Install it with: go install github.com/wailsapp/wails/v2/cmd/wails@v2.16.0" >&2
    exit 1
  fi
done

if [ ! -f "${FRONT_DIR}/package.json" ]; then
  echo "Frontend submodule is missing, initializing it..."
  git -C "${ROOT_DIR}" submodule update --init --recursive
fi

echo "==> Building frontend"
cd "${FRONT_DIR}"
npm ci
npm run build

echo "==> Copying frontend bundle into the desktop app"
# Replace the embedded bundle completely so stale hashed assets do not pile up.
# wailsjs/ is regenerated by `wails build`.
rm -rf "${EMBED_DIR}"
mkdir -p "${EMBED_DIR}"
cp -R "${FRONT_DIR}/dist/." "${EMBED_DIR}/"

echo "==> Building macOS app (universal)"
cd "${DESKTOP_DIR}"
wails build -platform darwin/universal -clean

echo "==> Packaging DMG"
bash packaging/darwin/build-dmg.sh "${OUTPUT_DMG}"
